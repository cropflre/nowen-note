import { test, expect } from "@playwright/test";
import fs from "node:fs";
import path from "node:path";

const evidence = path.resolve("../docs/qa/files-assets-center-v2/screenshots");
test("real product explorer: folders, masonry, details, move, upload queue and responsive themes", async ({ page, request, browser }) => {
  fs.mkdirSync(evidence, { recursive: true });
  const login = await request.post("/api/auth/login", { data: { username: "assets_qa", password: "assets-qa-only-password" } });
  expect(login.ok()).toBe(true);
  const account = await login.json() as { token: string; refreshToken: string };
  const headers = { Authorization: `Bearer ${account.token}` };
  await page.addInitScript((tokens) => {
    localStorage.setItem("nowen-token", tokens.token);
    localStorage.setItem("nowen-refresh-token", tokens.refreshToken);
    localStorage.setItem("i18nextLng", "zh-CN");
    localStorage.setItem("nowen-seen-version", tokens.version);
  }, { ...account, version: (JSON.parse(fs.readFileSync(path.resolve("../package.json"), "utf8")) as { version: string }).version });
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByRole("button", { name: "插入加密内容", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "文件管理", exact: true }).click();
  await expect(page.getByRole("heading", { name: "全部文件", exact: true })).toBeVisible({ timeout: 15_000 });
  await expect(page.locator("main footer")).toContainText("103 个文件");
  const initialImages = await (await request.get("/api/files?category=image", { headers })).json() as { items: Array<{ id: string; filename: string }>; accessUrls: Record<string, string> };
  const original = initialImages.items.find((image) => image.filename === "项目参考图-1.png")!;
  const originalBytes = await (await request.get(initialImages.accessUrls[original.id])).body();
  await page.screenshot({ path: path.join(evidence, "all-files.png") });
  await page.getByRole("button", { name: "项目资料", exact: true }).first().click();
  await page.getByRole("button", { name: "设计素材", exact: true }).first().click();
  await page.getByRole("button", { name: "参考图片", exact: true }).first().click();
  await expect(page.getByRole("navigation", { name: "文件路径" })).toContainText("项目资料");
  await expect(page.locator("main footer")).toContainText("6 个文件");
  await page.screenshot({ path: path.join(evidence, "folder-navigation.png") });
  await page.getByRole("button", { name: "新建文件夹", exact: true }).last().click();
  const createFolder = page.getByRole("dialog", { name: "新建文件夹", exact: true });
  await createFolder.getByRole("textbox", { name: "文件夹名称", exact: true }).fill("界面验收子目录");
  await createFolder.getByRole("button", { name: "保存", exact: true }).click();
  await expect(createFolder).toBeHidden();
  await expect(page.getByRole("button", { name: "界面验收子目录", exact: true }).first()).toBeVisible();
  await page.getByRole("button", { name: "图片", exact: true }).click();
  await page.getByRole("button", { name: "瀑布流视图", exact: true }).click();
  await expect(page.locator('img[src*="w=240"]').first()).toBeVisible();
  await page.screenshot({ path: path.join(evidence, "image-masonry.png") });
  await page.getByRole("button", { name: "项目参考图-1.png", exact: true }).click();
  await expect(page.getByText("项目开发记录", { exact: true }).last()).toBeVisible();
  await page.screenshot({ path: path.join(evidence, "file-details.png") });
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "项目参考图-1.png", exact: true }).click({ button: "right" });
  await page.getByRole("menuitem", { name: "移动文件", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "移动文件", exact: true });
  await expect(dialog.getByRole("button", { name: "项目资料 / 设计素材 / 参考图片", exact: true })).toBeVisible();
  await page.screenshot({ path: path.join(evidence, "move-dialog.png") });
  await dialog.getByRole("button", { name: "文档归档", exact: true }).click();
  await dialog.getByRole("button", { name: "移动文件", exact: true }).click();
  await expect(dialog).toBeHidden();
  const images = await (await request.get("/api/files?category=image", { headers })).json() as { items: Array<{ id: string; filename: string; folderId: string }> };
  expect(images.items.find((image) => image.filename === "项目参考图-1.png")?.folderId).toBe("qa-documents");
  expect(images.items.find((image) => image.filename === "项目参考图-1.png")?.id).toBe(original.id);
  expect(await (await request.get(initialImages.accessUrls[original.id])).body()).toEqual(originalBytes);

  await page.getByRole("button", { name: "文档", exact: true }).click();
  await expect(page.getByRole("button", { name: "列表视图", exact: true })).toHaveAttribute("aria-pressed", "true");
  const picker = page.locator('main input[type="file"]');
  await picker.setInputFiles(Array.from({ length: 100 }, (_, index) => ({ name: `批量上传-${index + 1}.txt`, mimeType: "text/plain", buffer: Buffer.from(`Unique batch attachment ${index}`) })));
  await expect(page.locator('[data-upload-status="success"]')).toHaveCount(100, { timeout: 60_000 });
  await picker.setInputFiles([
    { name: "拒绝类型验收.exe", mimeType: "application/x-msdownload", buffer: Buffer.from("invalid fixture") },
    { name: "失败后继续验收.txt", mimeType: "text/plain", buffer: Buffer.from("continue after rejected upload") },
  ]);
  await expect(page.locator('[data-upload-status="failed"]')).toHaveCount(1);
  await expect(page.locator('[data-upload-status="success"]')).toHaveCount(101);
  await page.getByRole("button", { name: "文档归档", exact: true }).first().click();
  await picker.setInputFiles({ name: "重复上传验收.txt", mimeType: "text/plain", buffer: Buffer.from("Unique batch attachment 0") });
  await expect(page.locator('[data-upload-status="existing"]')).toHaveCount(1);
  await expect(page.getByText("此文件已存在于「未整理」中。", { exact: true })).toBeVisible();
  const existing = await (await request.get("/api/files?q=批量上传-1.txt", { headers })).json() as { items: Array<{ folderId: string | null }> };
  expect(existing.items[0].folderId).toBeNull();
  await page.getByRole("button", { name: "文档", exact: true }).click();
  await page.screenshot({ path: path.join(evidence, "upload-queue-completed.png") });
  const client = await page.context().newCDPSession(page);
  await client.send("Network.enable");
  await client.send("Network.emulateNetworkConditions", { offline: false, latency: 50, downloadThroughput: 1024 * 1024, uploadThroughput: 128 * 1024 });
  await picker.setInputFiles({ name: "上传进度验收.txt", mimeType: "text/plain", buffer: Buffer.alloc(1024 * 1024, 65) });
  await expect(page.locator('[data-upload-status="uploading"] progress')).toBeVisible();
  await page.screenshot({ path: path.join(evidence, "upload-progress.png") });
  await expect(page.locator('[data-upload-status="uploading"]')).toHaveCount(0, { timeout: 30_000 });
  const documents = await (await request.get("/api/files?fileKind=document", { headers })).json() as { total: number };
  await expect(page.locator("main footer")).toContainText(`${documents.total} 个文件`);
  await client.send("Network.emulateNetworkConditions", { offline: false, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.keyboard.press("Escape");
  await page.screenshot({ path: path.join(evidence, "mobile-files.png") });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1600, height: 950 });
  await page.evaluate(() => document.documentElement.classList.add("dark"));
  await page.screenshot({ path: path.join(evidence, "dark-files.png") });
  const englishContext = await browser.newContext({ viewport: { width: 1280, height: 820 } });
  await englishContext.addInitScript((tokens) => {
    localStorage.setItem("nowen-token", tokens.token);
    localStorage.setItem("nowen-refresh-token", tokens.refreshToken);
    localStorage.setItem("i18nextLng", "en");
    localStorage.setItem("nowen-seen-version", tokens.version);
  }, { ...account, version: (JSON.parse(fs.readFileSync(path.resolve("../package.json"), "utf8")) as { version: string }).version });
  const english = await englishContext.newPage();
  await english.goto("http://127.0.0.1:4197/");
  await expect(english.getByRole("button", { name: /Insert encrypted content|插入加密内容/, exact: true })).toBeVisible();
  await english.getByLabel("Files", { exact: true }).click();
  await expect(english.getByRole("heading", { name: "All files", exact: true })).toBeVisible();
  await english.screenshot({ path: path.join(evidence, "english-files.png") });
  await englishContext.close();
  expect(errors).toEqual([]);
});
