test("V3 collections isolate scopes, reject stale writes and restore migrations and retained uninstall data", async () => {
  const service = getPluginService(), db = getDb(), id = "nowenlab.phase2";
  for (const actor of ["phase2-owner", "phase2-other"]) db.prepare("INSERT INTO users(id,username,passwordHash,role) VALUES (?,?,?,'admin')").run(actor, actor, "hash");
  await service.install(await examplePackage(id), "phase2-owner");
  service.grantPermissions(id, ["plugin-storage:read", "plugin-storage:write"], "phase2-owner");
  await service.enable(id);
  const call = (method: string, args: Record<string, unknown> = {}, userId = "phase2-owner", workspaceId: string | null = null) => service.broker.call({ pluginId: id, executionId: "data-test", actionId: "ui", userId, workspaceId }, { method, args });
  const empty: any = await call("data.query", { collection: "items" });
  assert.equal(empty.schemaVersion, 1); assert.equal(empty.total, 0);
  const a: any = await call("data.put", { collection: "items", id: "one", schemaVersion: 1, expectedRevision: 0, value: { title: "First", group: "work", status: "open" } });
  assert.equal(a.revision, 1);
  await assert.rejects(call("data.put", { collection: "items", id: "one", schemaVersion: 1, expectedRevision: 0, value: { title: "Stale" } }), (e: any) => e.code === "PLUGIN_DATA_CONFLICT");
  assert.equal((await call("data.query", { collection: "items" }, "phase2-other") as any).total, 0);
  await assert.rejects(call("data.query", { collection: "items", scopeId: "phase2-other" }), (e: any) => e.code === "PLUGIN_DATA_INVALID");
  await assert.rejects(call("storage.set", { key: "__nowen_collection__:items", value: {} }), (e: any) => e.code === "PLUGIN_DATA_INVALID");
  const filtered: any = await call("data.query", { collection: "items", where: { group: "work" }, orderBy: "title", limit: 1 });
  assert.equal(filtered.items[0].value.title, "First");
  const migrated: any = await call("data.migrate", { collection: "items", expectedRevision: filtered.revision, fromVersion: 1, toVersion: 2, defaults: { priority: "normal" } });
  assert.equal(migrated.schemaVersion, 2);
  await assert.rejects(call("data.put", { collection: "items", id: "two", schemaVersion: 1, expectedRevision: 0, value: {} }), (e: any) => e.code === "PLUGIN_DATA_CONFLICT");
  const restored: any = await call("data.restore", { collection: "items", expectedRevision: migrated.revision });
  assert.equal(restored.schemaVersion, 1); assert.ok(restored.items[0].revision > a.revision);
  const snapshot: any = await call("data.export");
  const corrupt = structuredClone(snapshot); corrupt.entries[0].value.records[0].revision += 100;
  await assert.rejects(call("data.import", { snapshot: corrupt, expectedDigest: snapshot.digest }), (e: any) => e.code === "PLUGIN_DATA_INVALID");
  assert.deepEqual(await call("data.export"), snapshot);
  db.exec(`CREATE TRIGGER phase2_write_failure BEFORE INSERT ON plugin_storage WHEN NEW.pluginId='nowenlab.phase2' BEGIN SELECT RAISE(ABORT,'test-write-failure'); END`);
  await assert.rejects(call("data.import", { snapshot, expectedDigest: snapshot.digest }), /test-write-failure/);
  assert.deepEqual(await call("data.export"), snapshot);
  db.exec("DROP TRIGGER phase2_write_failure");
  await assert.rejects(call("data.import", { snapshot, expectedDigest: "stale" }), (e: any) => e.code === "PLUGIN_DATA_CONFLICT");
  await assert.rejects(call("data.put", { collection: "items", id: "big", schemaVersion: 1, expectedRevision: 0, value: { body: "x".repeat(5000) } }), (e: any) => e.code === "PLUGIN_DATA_QUOTA_EXCEEDED");
  const temporary: any = await call("data.put", { collection: "items", id: "temporary", schemaVersion: 1, expectedRevision: 0, value: { title: "temporary" } });
  await call("data.delete", { collection: "items", id: "temporary", schemaVersion: 1, expectedRevision: temporary.revision });
  const recreated: any = await call("data.put", { collection: "items", id: "temporary", schemaVersion: 1, expectedRevision: 0, value: { title: "recreated" } });
  assert.ok(recreated.revision > temporary.revision);
  await assert.rejects(call("data.put", { collection: "items", id: "temporary", schemaVersion: 1, expectedRevision: temporary.revision, value: {} }), (e: any) => e.code === "PLUGIN_DATA_CONFLICT");
  await call("data.delete", { collection: "items", id: "temporary", schemaVersion: 1, expectedRevision: recreated.revision });
  db.prepare("INSERT INTO workspaces(id,name,ownerId) VALUES ('phase2-space','Phase2','phase2-owner')").run();
  db.prepare("INSERT INTO workspace_members(workspaceId,userId,role) VALUES ('phase2-space','phase2-owner','owner'),('phase2-space','phase2-other','viewer')").run();
  await call("data.put", { collection: "items", id: "shared", schemaVersion: 1, expectedRevision: 0, value: { title: "Workspace item" } }, "phase2-owner", "phase2-space");
  assert.equal((await call("data.query", { collection: "items" }, "phase2-other", "phase2-space") as any).items[0].value.title, "Workspace item");
  await assert.rejects(call("data.put", { collection: "items", id: "no", schemaVersion: 1, expectedRevision: 0, value: {} }, "phase2-other", "phase2-space"), (e: any) => e.code === "RESOURCE_FORBIDDEN");
  db.prepare("DELETE FROM workspace_members WHERE userId='phase2-other'").run();
  await assert.rejects(call("data.query", { collection: "items" }, "phase2-other", "phase2-space"), (e: any) => e.code === "RESOURCE_FORBIDDEN");
  db.prepare("INSERT INTO workspace_members(workspaceId,userId,role) VALUES ('phase2-space','phase2-other','viewer')").run();
  const app = new Hono(); app.route("/plugins", router);
  const headers = (user: string) => ({ Authorization: `Bearer ${user}`, "X-User-Id": user, "Content-Type": "application/json" });
  const actor = { userId: "phase2-owner", credential: crypto.createHash("sha256").update("Bearer phase2-owner").digest("hex") };
  const session = service.appRuntime.create(id, "home", actor, { platform: "web" });
  const mine: any = await (await app.request(`/plugins/data/${id}/export?workspaceId=personal`, { headers: headers("phase2-owner") })).json();
  const other: any = await (await app.request(`/plugins/data/${id}/export?workspaceId=personal`, { headers: headers("phase2-other") })).json();
  assert.equal(mine.entries.length, 1); assert.deepEqual(other.entries, []);
  const shared: any = await (await app.request(`/plugins/data/${id}/export?workspaceId=phase2-space`, { headers: headers("phase2-other") })).json();
  const forbidden = await app.request(`/plugins/data/${id}/import`, { method: "POST", headers: headers("phase2-other"), body: JSON.stringify({ workspaceId: "phase2-space", snapshot: shared, expectedDigest: shared.digest }) });
  assert.equal(forbidden.status, 403);
  assert.ok(service.appRuntime.check(session.instanceId, session.nonce, actor));
  const imported = await app.request(`/plugins/data/${id}/import`, { method: "POST", headers: headers("phase2-owner"), body: JSON.stringify({ workspaceId: "personal", snapshot: mine, expectedDigest: mine.digest }) });
  assert.equal(imported.status, 200); assert.throws(() => service.appRuntime.check(session.instanceId, session.nonce, actor));
  const otherScope: any = await call("data.export", {}, "phase2-other");
  const fullSnapshot = { ...otherScope, entries: Array.from({ length: 1000 }, (_, i) => ({ key: "key-" + i, value: "x".repeat(160) })) };
  await call("data.import", { snapshot: fullSnapshot, expectedDigest: otherScope.digest }, "phase2-other");
  const fullExport: any = await call("data.export", {}, "phase2-other");
  assert.equal(fullExport.entries.length, 1000); assert.ok(Buffer.byteLength(JSON.stringify(fullExport)) < 256 * 1024);
  await call("data.import", { snapshot: fullExport, expectedDigest: fullExport.digest }, "phase2-other");
  await assert.rejects(call("storage.set", { key: "over-limit", value: 1 }, "phase2-other"), (e: any) => e.code === "PLUGIN_DATA_QUOTA_EXCEEDED");
  await service.disable(id); await service.enable(id);
  assert.equal((await call("data.query", { collection: "items" }) as any).total, 1);
  await service.uninstall(id, false, true);
  assert.equal(service.registry.get(id), undefined);
  await service.install(await examplePackage(id), "phase2-owner");
  service.grantPermissions(id, ["plugin-storage:read", "plugin-storage:write"], "phase2-owner"); await service.enable(id);
  assert.equal((await call("data.query", { collection: "items" }) as any).items[0].value.title, "First");
  await service.uninstall(id, true);
  assert.equal(db.prepare("SELECT 1 FROM plugin_retained_storage WHERE pluginId=?").get(id), undefined);
  closeDb();
});

test("V3 widget declarations reject foreign page references and undeclared storage access", () => {
  const manifest = JSON.parse(require("node:fs").readFileSync(require("node:path").resolve("../examples/plugins/hello-nowen-app/manifest.json"), "utf8"));
  manifest.contributes.widgets = [{ id: "summary", title: "Summary", type: "statistic", pageId: "home", collection: "items", defaultSize: "small" }];
  assert.equal((parsePluginManifest(manifest) as any).contributes.widgets[0].id, "summary");
  manifest.contributes.widgets[0].pageId = "foreign"; assert.throws(() => parsePluginManifest(manifest));
  manifest.contributes.widgets[0].pageId = "home"; manifest.permissions = []; manifest.contributes.appPages[0].requiredPermissions = [];
  assert.throws(() => parsePluginManifest(manifest));
});

test("retained storage migration is repeatable and included in SQLite backup restoration", async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "nowen-plugin-backup-"));
  assert.equal(path.dirname(directory), path.resolve(os.tmpdir()));
  const db = new Database(":memory:");
  try {
    db.exec("CREATE TABLE plugin_storage(value TEXT); INSERT INTO plugin_storage VALUES ('legacy data')");
    pluginRetainedStorageMigration.up(db); pluginRetainedStorageMigration.up(db);
    assert.equal((db.prepare("SELECT value FROM plugin_storage").get() as any).value, "legacy data");
    db.prepare("INSERT INTO plugin_retained_storage VALUES ('nowenlab.test','nowenlab','user','owner','message','saved','now')").run();
    const file = path.join(directory, "snapshot.db"); await db.backup(file);
    const restored = new Database(file);
    try { assert.equal((restored.prepare("SELECT value FROM plugin_retained_storage").get() as any).value, "saved"); } finally { restored.close(); }
  } finally { db.close(); fs.rmSync(directory, { recursive: true, force: true }); }
});
